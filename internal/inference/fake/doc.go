// Package fake 是推理引擎的确定性替身，**只在带 keel_fake_embedder 标签时存在**。
//
// 这个文件是这个包在默认构建里的全部内容：一个包声明，没有任何类型、
// 没有任何函数。实现在 fake.go，那个文件的第一行是
//
//	//go:build keel_fake_embedder
//
// 所以默认构建里 fake.Embedder 这个名字**不存在**，谁想在生产代码里用它，
// 拿到的是一个编译错误，不是一个悄悄生效的假引擎。
//
// ## 为什么替身必须够不着
//
// 替身的用途是让测试不必每跑一次就下载 2.2 GB 权重、不必等 CPU 上的几秒。
// 它的产出是**确定性的伪随机单位向量**——维度对、范数是 1、同样的输入永远
// 得到同样的输出。也就是说它能通过这个仓库为向量设的每一道形状闸门，
// 唯独通不过「语义相近的两条文本向量也相近」那一条（见 fake_semantic_test.go）。
//
// 而它一旦能在生产路径上被选中，出的事恰恰不会报错：商品照常索引、
// 向量照常入库、搜索照常返回结果——只是返回的商品和你搜的词毫无关系。
// 这正是 M3 计划第二条要消灭的那类东西。
//
// ## 两道闸门，一道编译期一道构建图
//
//	① 编译标签：默认构建里这个包是空的。生产代码 import 它并调用，
//	   `go build ./...` 当场失败。
//	② internal/inference/nofake_test.go 的两条测试：
//	   一条核对 fake.go 真的还带着那个标签（有人把它删掉时红的是它），
//	   一条核对 ./cmd/keel 的依赖闭包里没有这个包。
//
// 这条纪律与 KEEL_DTM_DSN「没有默认值、空着拒绝启动」是同一条：
// 一个「反正能跑起来」的默认值，会让每个忘了配它的部署安静地拿到坏结局。
