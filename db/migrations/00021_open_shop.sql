-- 开店：把 merchants 上的 INSERT 还给 keel_app（契约 POST /admin/merchants）。
--
-- =============================================================================
-- 这一份迁移只有一行 GRANT，而那一行是 M4 收尾里唯一一次真正的安全取舍
-- =============================================================================
--
-- merchants 是 tenant-root 类（db/tenancy.json）：它刻意**没有** RLS —— 租户
-- 解析必须在 SET LOCAL 之前读它，挂上策略的话 current_merchant() 会在解析期
-- RAISE，整站在第一跳 404。防护因此整个压在 GRANT 面上，而 00005 把这张表的
-- 写权限收成了零，文件头原话：「解析层需要 SELECT，所以只收写权限。建店、
-- 迁移、种子走的是管理员角色。」
--
-- 那句话当时是对的，因为当时**没有建店这条路**。现在有了，而它必须由应用
-- 进程（keel_app）执行。所以这一行 GRANT 是绕不开的，问题只是「以什么形状
-- 绕不开」。四条路，选了第一条。
--
-- ### ① GRANT INSERT（本迁移采用）
--
-- 判据是 00005 那三条**实测**越权到底需要什么权限：
--
--     租户 1 的上下文里改租户 2 的 domain（域名劫持）→ UPDATE shop_settings
--     租户 1 的上下文里把租户 2 停用（全站 DoS）     → UPDATE merchants
--     完全没有租户上下文时改 merchants               → UPDATE merchants
--
-- **三条全部需要 UPDATE，一条都不需要 INSERT。** 00005 把三权一起收掉是对的
-- （当时一个写入者都没有，最小权限就是零），但它的威胁模型从头到尾说的是
-- **已经存在的那些行**，而 INSERT 按定义碰不到任何一行已有数据。
--
-- 新增的暴露面写清楚，不含糊：keel_app 从此能往 merchants 插行。它插不出
-- 别人的行、改不了任何已有行（没有 UPDATE / DELETE）、也没有拿到任何新的读
-- 权限（merchants 本来就人人可读，那就是 tenant-root 的定义）。而新插的那一
-- 行在有人往它的作用域里建出第一个 staff 之前是**惰性**的：没有 staff 就没有
-- 后台会话，没有会话就没有任何一条写接口进得去。也就是说这条权限最坏的滥用
-- 结果是「库里多一行没人能用的店」，外加占掉一个 code。
--
-- ### ② 用管理员角色（keel）另开一个连接池
--
-- **两个理由，第二个是硬的。**
--
-- 一、internal/db.Guard 会当场拒绝：那个角色 rolsuper / rolbypassrls 为真。
--     绕过 Guard 建池，等于让应用进程常驻握着一份能绕过**全库** RLS 的凭据 ——
--     那正是 Guard 存在的全部理由，也是 00017 否掉 BYPASSRLS 那条路时用的
--     同一个论证（「BYPASSRLS 给的是全部表的全部行」）。
-- 二、**它做不到「一个事务」。** 契约要求建店与建这家店的第一个管理员一起
--     成立：在两条连接上就是两个事务，而它们之间崩一次，留下的是一家谁也
--     进不去、也删不掉（没有 DELETE 权）的店。
--
-- ### ③ SECURITY DEFINER 函数（owner = 迁移角色）
--
-- 它确实比 ① 更窄：函数体是固定的一条 INSERT，列值由函数决定，调用方连
-- status 都传不进来。但它把「keel_app 能做什么」从 GRANT 面搬进了函数体，
-- 而这两者在这个仓库里的待遇差着一整道闸门：GRANT 面有
-- TestAppRoleGrantSurface 按 db/tenancy.json 逐表比对，多给少给都会红；
-- 函数体没有任何东西在看。scripts/check_query_tenancy.py 的文件头已经把这
-- 件事写在纸上了 —— 「这个检查挡不住别的绕过 RLS 的写法（比如 SECURITY
-- DEFINER 函数）」。
--
-- 更要紧的是 owner 是超级用户，函数体在库里就是一段能绕过全部 RLS 的代码。
-- 为了省掉一条**碰不到任何已有行**的 INSERT 权限，换来一段谁也检查不了的
-- 提权代码，这笔账是亏的。
--
-- ### ④ 给 merchants 挂 RLS，只允许平台作用域写
--
-- 与 tenant-root 这个类别的定义直接冲突，见本文件开头：解析层要在确定租户
-- **之前**读它。挂上策略的第一个后果不是「写被挡住了」，是整站第一跳 404。
--
-- =============================================================================
-- 为什么**不**连 shop_settings 一起给
-- =============================================================================
--
-- 因为开店这条路不写它。契约的 MerchantCreateRequest 只有 code / name /
-- admin_email，没有 domain；而 shop_settings 每一列都有默认值，插一行全默认
-- 值的记录与没有这一行在行为上完全一样（域名解析走 LEFT JOIN，支付密钥读
-- 出来是空）。也就是说那条 INSERT 权限换不到任何东西，而它守着的恰恰是
-- 00005 三条实测越权里最贵的那一条（自定义域名是全局物理资源，两家店绑同
-- 一个域名就是真的互相劫持）。
--
-- 新店因此没有自定义域名，只能走 {code}.KEEL_BASE_DOMAIN 或 /s/{code}。
-- 契约里 Merchant.domain 是可选字段，缺席就是「还没绑」，那是真话。

-- +goose Up

-- 只 INSERT。UPDATE / DELETE 仍然属于管理员角色（迁移与种子）。
GRANT INSERT ON merchants TO keel_app;

-- +goose Down
REVOKE INSERT ON merchants FROM keel_app;
