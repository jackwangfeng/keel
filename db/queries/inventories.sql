-- 文件留着，是因为 db/queries 里几十处注释引用「这个文件的第三条说明」。三条说明原样保留：
--
-- 一、同一张表在一条语句里出现两次（两个 CTE 各引用一次）时各带一个别名。sqlc 的作用域解析
--     把整条语句的关系拍平成一张表，同一张表出现两次就让每个裸列名都报
--     "column reference ... is ambiguous"，生成直接失败。PostgreSQL 自己没有
--     这个问题（两个 CTE 是各自独立的作用域）。
--
-- 二、要回一个「可能为空」的 CTE 结果时，写 「FROM (SELECT 1) a LEFT JOIN cte d ON true」，
--     不写 「(SELECT x FROM cte) AS y」：sqlc 会把那个标量子查询推断成**非空**，而它在
--     失败那一支恰恰是 NULL，于是 row.Scan 会在最该被区分开的那条路径上直接报错。
--     LEFT JOIN 让可空性显式地写在 SQL 里，产物才是指针类型。
--     「(SELECT 1) a」 保证外层恒有且只有一行，所以这种查询永远不会返回 0 行。
--
-- 三、注释里一个反引号都不许有。sqlc 会把这些注释原样抄进产物的 Go 文档注释，
--     而 scripts/check_query_tenancy.py 扫产物时用的是「一对反引号之间是 SQL
--     字面量」这条规则——注释里的反引号会被配对成一段假的字面量，于是
--     「完全没设 app.merchant_id 时」这句话被当成一句应用层租户过滤报出来。
--     多报一次是安全的失败方向，所以不改那个脚本，改这里：用「」代替反引号。
